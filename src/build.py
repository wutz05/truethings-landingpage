def sprite(name: str, alt: str = "", cls: str = "", width: int | None = None, eager: bool = False, style: str = "") -> str:
    """A pixel Thing from assets/img/things (392 × 392, pairs 584 × 384)."""
    w, h = (584, 384) if name.startswith("pair-") else (392, 392)
    loading = "" if eager else ' loading="lazy"'
    css = ";".join(x for x in (f"width:{width}px" if width else "", style) if x)
    style_attr = f' style="{css}"' if css else ""
    return (f'<img class="sprite {cls}" src="{asset(f"/assets/img/things/{name}.png")}" alt="{esc(alt)}"'
            f' width="{w}" height="{h}"{loading} decoding="async"{style_attr}>')


