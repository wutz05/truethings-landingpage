def pixel_svg(rows: list[str], cls: str = "", color: str = "currentColor", hi: str = "#fff", extra: str = "") -> str:
    w, h = len(rows[0]), len(rows)
    rects = []
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "X":
                rects.append(f'<rect x="{x}" y="{y}" width="1.02" height="1.02"/>')
            elif c == "o":
                rects.append(f'<rect x="{x}" y="{y}" width="1.02" height="1.02" opacity=".4"/>')
            elif c == "w":
                rects.append(f'<rect x="{x}" y="{y}" width="1.02" height="1.02" fill="{hi}"/>')
    return (f'<svg class="{cls}" viewBox="0 0 {w} {h}" fill="{color}" aria-hidden="true" focusable="false"'
            f' shape-rendering="crispEdges"{extra}>{"".join(rects)}</svg>')


def icon(name: str, hi: str = "var(--surface)") -> str:
    return pixel_svg(ICONS[name], hi=hi)


PIX_COLORS = {"cream": "#FFE5DF", "pink": "#FF8FC0", "hot": "#FF5AB3", "coral": "#FF8A73", "gold": "#FFD25E",
              "sky": "#9CC8FF", "lilac": "#C9A8FF"}


def scatter(items: list[tuple]) -> str:
    """Pixel motifs on a plum background: (kind, left %, top %, cell px, colour, opacity)."""
    out = []
    for kind, left, top, cell, color, opacity in items:
        rows = PIX[kind]
        w, h = len(rows[0]) * cell, len(rows) * cell
        out.append(pixel_svg(rows, cls="pix", color=PIX_COLORS[color], hi="rgba(255,255,255,.65)",
                             extra=f' style="left:{left}%;top:{top}%;width:{w}px;height:{h}px;opacity:{opacity}"'))
    return "".join(out)


