def esc(text: str) -> str:
    return html.escape(text, quote=True)


def strip_tags(text: str) -> str:
    return re.sub(r"<[^>]+>", "", text)


def asset(path: str) -> str:
    """Root-relative asset URL with a content hash, so the year-long cache never serves stale files."""
    file = ROOT / path.lstrip("/")
    if not file.exists():
        return path
    digest = hashlib.sha1(file.read_bytes()).hexdigest()[:8]
    return f"{path}?v={digest}"


def url(path: str) -> str:
    return BASE + ("/" if path == "/" else path)


def out_file(path: str) -> Path:
    if path == "/":
        return ROOT / "index.html"
    if path in ("/de", "/de/blog"):
        return ROOT / path.lstrip("/") / "index.html"
    return ROOT / (path.lstrip("/") + ".html")


