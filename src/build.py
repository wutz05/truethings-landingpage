def write_page(*, lang: str, path: str, title: str, description: str, body: str, alternates: dict | None = None,
               og: dict | None = None, jsonld: list[dict] | None = None, active: str | None = None,
               scripts: tuple[str, ...] = (), indexable: bool = True, in_sitemap: bool = True,
               lastmod: str = SITE_UPDATED, og_type: str = "website", extra_head: str = "") -> None:
    alternates = alternates or {lang: path}
    canonical = url(path)
    og = og or {"key": f"default-{lang}", "kicker": C.HOME[lang]["kicker"], "title": strip_tags(C.HOME[lang]["h1"]), "art": "pair-in-love"}
    OG_JOBS[og["key"]] = {"lang": lang, "kicker": og["kicker"], "title": og["title"], "art": og.get("art", "pair-in-love")}
    og_image = f"{BASE}/assets/img/og/{og['key']}.jpg"

    head = [
        '<!doctype html>', GENERATED, f'<html lang="{lang}">', '<head>',
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
        f'<title>{esc(title)}</title>',
        f'<meta name="description" content="{esc(description)}">',
        f'<link rel="canonical" href="{canonical}">',
    ]
    if not indexable:
        head.append('<meta name="robots" content="noindex, follow">')
    if indexable and len(alternates) > 1:
        for l, p in sorted(alternates.items()):
            head.append(f'<link rel="alternate" hreflang="{l}" href="{url(p)}">')
        head.append(f'<link rel="alternate" hreflang="x-default" href="{url(alternates.get("en", path))}">')
    locale = "de_DE" if lang == "de" else "en_US"
    head += [
        f'<meta property="og:type" content="{og_type}">',
        '<meta property="og:site_name" content="TrueThings">',
        f'<meta property="og:locale" content="{locale}">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(description)}">',
        f'<meta property="og:url" content="{canonical}">',
        f'<meta property="og:image" content="{og_image}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{esc(og["title"])}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="apple-itunes-app" content="app-id={APP_ID}">',
        '<meta name="theme-color" content="#380935">',
        f'<link rel="icon" type="image/png" sizes="32x32" href="{asset("/assets/img/icon-32.png")}">',
        f'<link rel="icon" type="image/png" sizes="192x192" href="{asset("/assets/img/icon-192.png")}">',
        f'<link rel="apple-touch-icon" href="{asset("/assets/img/icon-180.png")}">',
        f'<link rel="stylesheet" href="{asset("/assets/css/site.css")}">',
    ]
    for block in jsonld or []:
        head.append('<script type="application/ld+json">' + json.dumps(block, ensure_ascii=False, separators=(",", ":")) + '</script>')
    if extra_head:
        head.append(extra_head)
    head.append("</head>")

    script_tags = "".join(f'<script src="{asset(s)}" defer></script>' for s in ("/assets/js/site.js", *scripts))
    doc = "\n".join(head) + "\n<body>\n" + header(lang, active, alternates) + \
        f'\n<main id="main">\n{body}\n</main>\n' + footer(lang, alternates) + "\n" + cookie_banner(lang) + \
        "\n" + script_tags + "\n</body>\n</html>\n"

    target = out_file(path)
    target.parent.mkdir(parents=True, exist_ok=True)
