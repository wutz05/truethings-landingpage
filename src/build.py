ALLOWED_TAGS = {"p", "h2", "h3", "ul", "ol", "li", "strong", "em", "a", "blockquote", "table", "thead", "tbody", "tr",
                "th", "td", "aside", "br"}


def load_posts() -> dict[str, list[dict]]:
    posts: dict[str, list[dict]] = {"de": []}
    folder = SRC / "content" / "blog" / "de"
    for file in sorted(folder.glob("*.html")) if folder.exists() else []:
        raw = file.read_text(encoding="utf-8")
        m = re.match(r"\s*<!--(.*?)-->", raw, re.S)
        if not m:
            raise SystemExit(f"{file}: missing JSON front matter")
        meta = json.loads(m.group(1))
        body = raw[m.end():].strip()
        for tag in set(re.findall(r"</?([a-zA-Z0-9]+)", body)):
            if tag.lower() not in ALLOWED_TAGS:
                print(f"warning: {file.name}: tag <{tag}> is not in the allowed list")
        words = len(re.findall(r"\w+", strip_tags(re.sub(r"<!--.*?-->", "", body))))
        slug = meta["slug"]
        posts["de"].append({
            **meta, "body": body, "words": words, "minutes": max(1, round(words / 220)),
            "path": f"/de/blog/{slug}", "og_key": f"blog-{slug}",
            "nav_title": meta.get("nav_title") or meta["og_title"],
        })
    posts["de"].sort(key=lambda p: (p["date"], p["title"]), reverse=True)
    return posts


