def breadcrumbs(items: list[tuple[str, str | None]]) -> str:
    lis = []
    for name, href in items:
        if href:
            lis.append(f'<li><a href="{href}">{esc(name)}</a></li>')
        else:
            lis.append(f'<li><span aria-current="page">{esc(name)}</span></li>')
    return f'<nav class="breadcrumbs" aria-label="Breadcrumb"><ol>{"".join(lis)}</ol></nav>'


def jsonld_breadcrumbs(items: list[tuple[str, str]]) -> dict:
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": name, "item": url(path)} for i, (name, path) in enumerate(items)]}


