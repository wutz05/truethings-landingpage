def render_post_body(post: dict) -> tuple[str, str, list[tuple[str, str]]]:
    """Returns (lead paragraph, body without it, table of contents)."""
    body = post["body"]
    lang = "de"
    t = C.UI[lang]
    lead = ""
    m = re.match(r'\s*<p class="lead">(.*?)</p>', body, re.S)
    if m:
        lead = m.group(1).strip()
        body = body[m.end():]

    # Number the question lists straight through the article ("150 Fragen" adds up on the page).
    counter = 0

    def number(m2: re.Match) -> str:
        nonlocal counter
        start = counter + 1
        counter += len(re.findall(r"<li>", m2.group(1)))
        return f'<ol class="questions" start="{start}">{m2.group(1)}</ol>'

    body = re.sub(r'<ol class="questions">(.*?)</ol>', number, body, flags=re.S)

    def app_cta(_m: re.Match) -> str:
        return (f'<aside class="inline-cta plum on-plum">{sprite("pair-in-love", "")}<div>'
                f'<h3>{esc("TrueThings: Spielt zusammen, auch auf Distanz")}</h3>'
                f'<p>{esc("Sieben Spiele live auf zwei Handys, Fragen für echte Gespräche und Notizen, die direkt im Widget deines Partners landen. Ein Abo für euch beide.")}</p>'
                f'<div class="cta-row">{store_badge(lang, "blog-inline")}</div></div></aside>')

    def deck_cta(m: re.Match) -> str:
        deck_id = m.group(1)
        spec = C.DECKS[deck_id]["de"]
        tint = DECK_DATA[deck_id]["tint"]
        return (f'<aside class="inline-cta deck t-{tint}"><span class="deck-swatch">{icon(C.DECKS[deck_id]["icon"])}</span><div>'
                f'<h3>{esc(spec["name"])}: {esc("kostenlos im Browser")}</h3><p>{esc(spec["teaser"])}</p>'
                f'<a class="btn btn-primary btn-sm" href="{spec["path"]}">{esc("Jetzt spielen")} <span class="arrow" aria-hidden="true">→</span></a>'
                f'</div></aside>')

    body = re.sub(r"<!--\s*cta:app\s*-->", app_cta, body)
